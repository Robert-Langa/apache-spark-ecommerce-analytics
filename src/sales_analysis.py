
from pyspark.sql import DataFrame
from pyspark.sql.functions import col, sum as spark_sum


def calculate_revenue(df: DataFrame) -> DataFrame:
    """
    Calculates the revenue generated by each transaction.

    Revenue = Quantity * Unit Price
    """

    # Create a new column called 'revenue'
    # by multiplying the quantity and unit price
    return df.withColumn(
        "revenue",
        col("quantity") * col("unit_price")
    )


def revenue_by_category(df: DataFrame) -> DataFrame:
    """
    Calculates total revenue for each product category.

    Returns the categories ordered from the
    highest revenue to the lowest.
    """

    return (
        df
        # Group all transactions by product category
        .groupBy("category")

        # Calculate the total revenue for each category
        .agg(
            spark_sum("revenue").alias("total_revenue")
        )

        # Sort categories by revenue in descending order
        .orderBy(col("total_revenue").desc())
    )
